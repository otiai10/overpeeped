import SwiftUI

/// マスコット種 — とかげ (lizard)。`mascot_model = "lizard"` で選択する試作モデル。
///
/// ドット絵は 16×16 グリッド。右向きの横顔 (chick の focused と同じ向き)。
/// - 凡例:
///   - `.` 透明
///   - `g` 緑 (体)、`G` 濃緑 (影・脚・斑点・アウトライン)、`l` 黄緑 (腹)
///   - `B` 黒 (目)、`W` 白 (目ハイライト)
///   - `r` 赤 (舌)、`s` キラキラ
///   - `a` 興奮色 (angry の体)、`A` 濃い興奮色、`k` 背びれの棘 (angry)
///   - `d` くすんだ淡色 (sad)、`D` くすんだ濃色、`t` 涙
struct LizardModel: MascotModel {
    let id = "lizard"
    let displayName = "とかげ"

    func frames(for emotion: Emotion) -> [PixelArt] {
        switch emotion {
        case .thinking:  return Self.focused
        case .focused:   return Self.focused
        case .expectant: return Self.expectant
        case .impatient: return Self.impatient
        case .angry:     return Self.angry
        case .sad:       return Self.sad
        case .happy:     return Self.happy
        case .lonely:    return Self.lonely
        case .sulking:   return Self.sulking
        }
    }

    /// とかげは舌をちろちろさせて鳴く。thinking / focused / sulking は無音。
    func cry(for emotion: Emotion) -> String? {
        switch emotion {
        case .thinking, .focused, .sulking: return nil
        case .expectant:                    return "ちろ?"
        case .impatient:                    return "ちろちろっ"
        case .angry:                        return "シャーッ!"
        case .sad:                          return "ち...ろ..."
        case .happy:                        return "ちろっ♪"
        case .lonely:                       return "ちろ..."
        }
    }

