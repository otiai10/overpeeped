    private static let palette: [Character: Color] = [
        "g": Color(red: 0.46, green: 0.73, blue: 0.33),  // leaf green / 体
        "G": Color(red: 0.27, green: 0.46, blue: 0.20),  // dark green / 影・脚・斑点
        "l": Color(red: 0.74, green: 0.87, blue: 0.55),  // light belly / 腹
        "B": Color(red: 0.10, green: 0.10, blue: 0.10),  // eye
        "W": Color.white,                                 // eye highlight
        "r": Color(red: 0.93, green: 0.32, blue: 0.40),  // tongue / 舌
        "s": Color(red: 1.00, green: 0.95, blue: 0.60),  // sparkle
        "a": Color(red: 0.66, green: 0.62, blue: 0.16),  // angry body / 興奮色
        "A": Color(red: 0.42, green: 0.37, blue: 0.10),  // angry dark
        "k": Color(red: 0.16, green: 0.24, blue: 0.10),  // spike / 背びれの棘
        "d": Color(red: 0.58, green: 0.63, blue: 0.54),  // sad dull / くすみ淡
        "D": Color(red: 0.42, green: 0.46, blue: 0.39),  // sad dull dark
        "t": Color(red: 0.40, green: 0.64, blue: 0.98),  // tear
    ]

    private static func art(_ ascii: String) -> PixelArt {
        mascotPixelArt(ascii, palette: palette)
    }

